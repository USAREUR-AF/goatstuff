// ---------------------------------------------------------------------------
// garage-door — homemade-sensors/garage/door-state/v1 (subscribes to
// the sibling temperature topic so panoscope shows an intra-vendor edge).
// ---------------------------------------------------------------------------

#[derive(Debug, Default)]
struct DoorState {
    open: bool,
    last_change_ms: u64,
}

#[derive(Serialize)]
struct GarageDoorPayload {
    sensor_id: String,
    ts_ms: u64,
    state: &'static str,
    last_change_ms: u64,
    duration_s: u64,
    related_topics_seen: Vec<String>,
}

fn render_garage_door(
    peer_id: &str,
    state: &mut DoorState,
    related_topics: Vec<String>,
    rng: &mut rand::rngs::StdRng,
) -> Vec<u8> {
    // ~20% chance of state toggle per tick; otherwise the door stays where
    // it was. Initial state defaults to closed.
    if rng.gen_bool(0.2) {
        state.open = !state.open;
        state.last_change_ms = now_ms();
    }
    if state.last_change_ms == 0 {
        state.last_change_ms = now_ms();
    }
    let duration_s = (now_ms().saturating_sub(state.last_change_ms)) / 1000;
    let body = GarageDoorPayload {
        sensor_id: peer_id.to_string(),
        ts_ms: now_ms(),
        state: if state.open { "open" } else { "closed" },
        last_change_ms: state.last_change_ms,
        duration_s,
        related_topics_seen: related_topics,
    };
    serde_json::to_vec(&body).unwrap_or_default()
}

