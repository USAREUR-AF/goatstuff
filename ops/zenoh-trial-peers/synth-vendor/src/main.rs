#[derive(Debug, Clone, Copy, ValueEnum, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
enum Personality {
    TracksDemo,
    PowerDemo,
    BeaconDemo,
    GarageTemp,
    GarageDoor,
    YardSoil,
    Observer,
}

impl Personality {
    /// The wire format of this personality's data payload, as a short tag.
    /// Single source of truth: drives BOTH the Zenoh sample `Encoding` (so
    /// consumers read the format off the wire instead of an out-of-band
    /// lookup, per docs/design/zenoh-capability-adoption.md) AND the
    /// `format` field of the `attest/schema/**` schema-decl. CBOR for
    /// YardSoil, JSON otherwise. (Personalities that emit protobuf return
    /// `"protobuf:<MsgName>"`; `wire_encoding` maps that to
    /// APPLICATION_PROTOBUF with the schema name attached.)
    fn wire_format(self) -> &'static str {
        match self {
            Personality::YardSoil => "cbor",
            _ => "json",
        }
    }

    /// Zenoh sample `Encoding` for this personality, derived from
    /// `wire_format()` so the wire is self-describing. `protobuf:<Msg>`
    /// tags carry the message name as the encoding schema suffix.
    fn wire_encoding(self) -> Encoding {
        format_to_encoding(self.wire_format())
    }

    /// CBOR-encoded personalities skip the JSON serialization path and
    /// emit a ciborium-packed payload instead. Exercises the inspector's
    /// CBOR decoder. Surface check (the dispatch in run_peer() already picks
    /// the right render_* per variant; this helper is for tests + future
    /// callers that need to predict the wire format up front).
    #[cfg(test)]
    fn is_cbor(self) -> bool {
        matches!(self, Personality::YardSoil)
    }
}

/// Map a schema-decl `format` tag to a Zenoh sample `Encoding`. Keeps the
/// publisher's wire encoding in lockstep with the declared format so the two
/// can never drift. `protobuf:<MsgName>` carries the message name as the
/// encoding schema suffix (`application/protobuf;<MsgName>`), which the
/// inspector decode path reads to pick a `.fds` without an out-of-band lookup.
fn format_to_encoding(format: &str) -> Encoding {
    match format {
        "cbor" => Encoding::APPLICATION_CBOR,
        "json" => Encoding::APPLICATION_JSON,
        other => {
            if let Some(msg) = other.strip_prefix("protobuf:") {
                Encoding::APPLICATION_PROTOBUF.with_schema(msg)
            } else if other == "protobuf" {
                Encoding::APPLICATION_PROTOBUF
            } else {
                Encoding::APPLICATION_OCTET_STREAM
            }
        }
    }
}

#[derive(Parser, Debug)]
#[command(name = "synth-vendor", about = "synthetic Zenoh peer for the trial fabric")]
struct Args {
    /// Path to a fleet roster (JSON). When set, this process drives EVERY
    /// peer in the roster, each in its own Zenoh session (distinct ZID), and
    /// the single-peer flags below are ignored. Built for the local
    /// containerised panoscope demo — one container, the whole ecosystem.
    #[arg(long, env = "SYNTH_VENDOR_ROSTER")]
    roster: Option<String>,

    /// Which personality to run (single-peer mode).
    #[arg(long, env = "SYNTH_VENDOR_PERSONALITY", value_enum)]
    personality: Option<Personality>,

    /// Zenoh router endpoint, e.g. `tls/127.0.0.1:7447` or `tcp/host:7447`.
    /// In fleet mode the roster's `endpoint` wins; this is the fallback.
    #[arg(long, env = "SYNTH_VENDOR_ENDPOINT")]
    endpoint: Option<String>,

    /// Topic key-expression to publish on (single-peer mode). Must be under
    /// the vendor's allowlisted prefix or the router ACL rejects the publish.
    #[arg(long, env = "SYNTH_VENDOR_TOPIC")]
    topic: Option<String>,

    /// Publish rate in Hz (can be fractional, e.g. 0.1 = once per 10s).
    #[arg(long, env = "SYNTH_VENDOR_RATE_HZ", default_value_t = 1.0)]
    rate_hz: f64,

    /// Pure-sink mode: subscribe (and emit schema-decls) but never publish a
    /// data topic. The schema-decl omits `publishes` so panoscope renders the
    /// peer as a subscriber-only sink. Mirrors SYNTH_VENDOR_NO_PUBLISH in the
    /// Ansible role (glass-display / archive-vault / audit-log).
    #[arg(long, env = "SYNTH_VENDOR_NO_PUBLISH", default_value_t = false)]
    no_publish: bool,

    /// Path to the per-vendor leaf X.509 certificate (PEM). Required when
    /// `endpoint` is `tls/...`; ignored otherwise.
    #[arg(long, env = "SYNTH_VENDOR_CERT")]
    cert: Option<String>,

    /// Path to the matching private key (PEM). Required when `endpoint`
    /// is `tls/...`; ignored otherwise.
    #[arg(long, env = "SYNTH_VENDOR_KEY")]
    key: Option<String>,

    /// Path to the goatnet CA root certificate (PEM) — used to verify
    /// the router's server cert. Required when `endpoint` is `tls/...`;
    /// ignored otherwise.
    #[arg(long, env = "SYNTH_VENDOR_ROOT_CA")]
    root_ca: Option<String>,

    /// Optional key-expression to subscribe to (used by beacon-demo to
    /// listen on `caracal/**`, garage-door on its sibling temperature
    /// topic, observer on `**`). Empty = no subscriber.
    #[arg(long, env = "SYNTH_VENDOR_SUBSCRIBE_KEY", default_value = "")]
    subscribe_key: String,

    /// Stable identifier for this peer's payloads (e.g. "tracks-demo-A").
    /// Surfaces as `entity_id` / `site_id` / `beacon_id` / `sensor_id` /
    /// `observer_id` depending on personality so panoscope and the
    /// audit-logger can correlate.
    #[arg(long, env = "SYNTH_VENDOR_PEER_ID")]
    peer_id: Option<String>,

    /// Logical role-taxonomy class consumed by panoscope to differentiate
    /// node shapes (sensor / effector / data-service / c2 / observer /
    /// sink). Without this, every synth-vendor falls back to Role::Source
    /// via the publish-only inference path and every node renders as a
    /// circle — exactly the regression the notional namespace
    /// collapse made visible. Optional; if absent the schema-decl simply
    /// omits the field and panoscope's role inference still runs.
    #[arg(long, env = "SYNTH_VENDOR_ROLE_CLASS", default_value = "")]
    role_class: String,

    /// Logical site this peer belongs to (e.g. "alpha-fob", "theater").
    /// Surfaces in the panoscope side panel so a single vendor identity
    /// spread across multiple sites is still visually navigable.
    #[arg(long, env = "SYNTH_VENDOR_SITE", default_value = "")]
    site: String,

    /// Friendly per-peer name (e.g. "tarsier-alpha") used as the
    /// panoscope node label. Distinct from `--peer-id` (which seeds the
    /// data-payload entity_id) and from the cert-bound vendor (which is
    /// uniform across all synth-vendor peers after the notional collapse).
    /// Defaults to `--peer-id` if not provided.
    #[arg(long, env = "SYNTH_VENDOR_DISPLAY_NAME", default_value = "")]
    display_name: String,

    /// Logical vendor display name carried in the schema-decl JSON
    /// `vendor` field. Decoupled from the cert-bound vendor on purpose:
    /// after the notional namespace collapse the cert vendor is uniform,
    /// but operators may still want to label a peer's logical vendor
    /// (e.g. "tarsier-sensors" or "notional"). Defaults to "notional".
    /// Field name mirrors the role-defaults `logical_vendor:` key.
    #[arg(long, env = "SYNTH_VENDOR_LOGICAL_VENDOR", default_value = "notional")]
    logical_vendor: String,

    /// Schema-decl re-publish interval in seconds. panoscope's
    /// SCHEMA_DECL_STALE_MS is 90s, so the default 30s gives 3× headroom
    /// for one missed publish before a peer goes stale.
    #[arg(long, env = "SYNTH_VENDOR_SCHEMA_DECL_INTERVAL_S", default_value_t = 30)]
    schema_decl_interval_s: u64,
}

/// Per-peer runtime configuration. Both run modes funnel into this so
/// run_peer() is identical whether the peer came from CLI flags or a row in
/// a fleet roster.
#[derive(Debug, Clone)]
struct PeerConfig {
    personality: Personality,
    topic: String,
    rate_hz: f64,
    subscribe_key: String,
    peer_id: String,
    role_class: String,
    site: String,
    display_name: String,
    logical_vendor: String,
    schema_decl_interval_s: u64,
    no_publish: bool,
}

impl PeerConfig {
    /// Panoscope node label — `display_name` if set, else `peer_id`.
    fn label(&self) -> String {
        if self.display_name.is_empty() {
            self.peer_id.clone()
        } else {
            self.display_name.clone()
        }
    }
}

/// Zenoh connection parameters shared by every peer in a process. In fleet
/// mode all peers connect to the same router over the same endpoint; only
/// their ZID (assigned by zenoh::open) and their payloads differ.
#[derive(Debug, Clone)]
struct ConnParams {
    endpoint: String,
    cert: Option<String>,
    key: Option<String>,
    root_ca: Option<String>,
}

/// A fleet roster — top-level connection params plus the peer list. Parsed
/// from JSON when --roster is set. The connection fields are optional here;
/// if absent they fall back to the CLI flags (so the endpoint can be
/// supplied by compose env while the peer list stays static in the image).
#[derive(Debug, Deserialize)]
struct Roster {
    #[serde(default)]
    endpoint: Option<String>,
    #[serde(default)]
    cert: Option<String>,
    #[serde(default)]
    key: Option<String>,
    #[serde(default)]
    root_ca: Option<String>,
    peers: Vec<RosterPeer>,
}

/// One row in a fleet roster. Field set mirrors the single-peer CLI flags
