// ---------------------------------------------------------------------------
// beacon-demo — encodes notional.beacon_demo.v1.Hello (matches
// topic.format on the portal). Observer-style: the same peer subscribes
// to `notional/**` and folds the last-30s topic set into its hello.
// ---------------------------------------------------------------------------

fn render_beacon_demo(
    peer_id: &str,
    observed_topics: Vec<String>,
    _rng: &mut rand::rngs::StdRng,
) -> Vec<u8> {
    static START: std::sync::OnceLock<u64> = std::sync::OnceLock::new();
    let start = *START.get_or_init(now_ms);
    let uptime_s = (now_ms().saturating_sub(start)) / 1000;
    let observed_count = observed_topics.len();
    let msg = proto_notional::beacon_demo::v1::Hello {
        beacon_id: peer_id.to_string(),
        ts_ms: now_ms(),
        uptime_s,
        message: format!(
            "hello from {peer_id} — observed {observed_count} notional topics in last 30s"
        ),
        observed_topics,
    };
    msg.encode_to_vec()
}

