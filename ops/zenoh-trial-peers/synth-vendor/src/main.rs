// synth-vendor — small synthetic publisher/subscriber for the
// Zenoh trial fabric. One binary, several personalities selected via
// --personality:
//
//   tracks-demo / power-demo / beacon-demo  — caracal + community vendors
//   garage-temp / garage-door / yard-soil   — homemade-sensors vendor
//   observer                                — pangolin vendor (subscriber + heartbeat)
//
// Per docs/design/zenoh-trial-fabric-synth-vendors.md:
//   - Opens an mTLS Zenoh session as a client peer of the trial router.
//   - Publishes a JSON (or CBOR for yard-soil) payload at the configured
//     rate on the configured topic. Payload shape matches the
//     corresponding schema in schemas/<personality>-v1.json.
//   - Personalities with --subscribe-key set ALSO subscribe — beacon-demo
//     listens on caracal/** (cross-vendor), garage-door listens on its
//     sibling temperature topic (intra-vendor "smart door" correlation),
//     power-demo listens on community/** (cross-vendor), and observer
//     listens on ** (everything) and publishes a heartbeat summarising
//     what it has seen.
//
// Two run modes:
//   - Single-peer (default): one --personality, one ZID per process. This
//     is what the Ansible role (ops/ansible/roles/zenoh-synth-vendors/)
//     drives — one container per notional peer.
//   - Fleet (--roster <file>): one process drives MANY peers, each in its
//     own Zenoh session (distinct ZID), so a single container can stand up
//     the whole notional ecosystem panoscope renders. Built for the local
//     containerised panoscope demo (ops/panoscope/
//     docker-compose.dev.yml) where running 22 separate containers on an
//     already-loaded laptop is wasteful. panoscope keys peers by ZID, so
//     N sessions in one process == N distinct nodes in the graph.
//     See docs/design/zenoh-trial-fabric-synth-vendors.md §"Fleet mode".
//
// Connection failures surface in logs but the loop persists — zenoh
// reconnects internally; we don't add layered backoff on top of that.

