// Command zenoh-ts-bundle writes one browser-loadable ES module from the
// unpacked @eclipse-zenoh/zenoh-ts package tree, using esbuild's Go API.
//
// The package cannot be loaded by a browser as published: it imports its
// dependencies by bare package name, and its key-expression code is
// wasm-bindgen "bundler" output, which imports a .wasm file as if it were a
// JavaScript module. esbuild resolves the bare imports; the plugin below
// supplies the .wasm module. No upstream file is edited.
//
// Usage: zenoh-ts-bundle <dir holding node_modules> <out.js>
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"github.com/evanw/esbuild/pkg/api"
)

const banner = "// Generated by ops/serve/zenoh-sandbox/vendor-tool/regenerate.sh from the\n" +
	"// packages pinned in packages.lock.json. Do not edit; see README.md beside this file."

// wasmPlugin stands in for a bundler's WebAssembly-module support. For an
// import of X_bg.wasm it generates a module that instantiates the embedded
// bytes against the sibling X_bg.js glue and re-exports each of the instance's
// exports by name. Paths inside the plugin's namespaces are relative to root,
// so the output does not depend on where the tree was unpacked.
func wasmPlugin(root string) api.Plugin {
	return api.Plugin{
		Name: "wasm-bindgen-bundler",
		Setup: func(b api.PluginBuild) {
			b.OnResolve(api.OnResolveOptions{Filter: `_bg\.wasm$`}, func(a api.OnResolveArgs) (api.OnResolveResult, error) {
				if a.PluginData == "bytes" {
					return api.OnResolveResult{Path: a.Path, Namespace: "wasm-bytes"}, nil
				}
				rel, err := filepath.Rel(root, filepath.Join(a.ResolveDir, a.Path))
				if err != nil {
					return api.OnResolveResult{}, err
				}
				return api.OnResolveResult{Path: filepath.ToSlash(rel), Namespace: "wasm-module"}, nil
			})
			b.OnLoad(api.OnLoadOptions{Filter: `.*`, Namespace: "wasm-module"}, func(a api.OnLoadArgs) (api.OnLoadResult, error) {
				abs := filepath.Join(root, filepath.FromSlash(a.Path))
				raw, err := os.ReadFile(abs)
				if err != nil {
					return api.OnLoadResult{}, err
				}
				names, err := wasmExports(raw)
				if err != nil {
					return api.OnLoadResult{}, fmt.Errorf("%s: %w", a.Path, err)
				}
				base := filepath.Base(abs)
				glue := "./" + base[:len(base)-len(".wasm")] + ".js"
				src := fmt.Sprintf("import bytes from %q;\nimport * as glue from %q;\n"+
					"const { instance } = await WebAssembly.instantiate(bytes, { %q: glue });\n", a.Path, glue, glue)
				for _, n := range names {
					src += fmt.Sprintf("export const %s = instance.exports[%q];\n", n, n)
				}
				return api.OnLoadResult{Contents: &src, ResolveDir: filepath.Dir(abs), Loader: api.LoaderJS, PluginData: "bytes"}, nil
			})
			b.OnLoad(api.OnLoadOptions{Filter: `.*`, Namespace: "wasm-bytes"}, func(a api.OnLoadArgs) (api.OnLoadResult, error) {
				raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(a.Path)))
				if err != nil {
					return api.OnLoadResult{}, err
				}
				s := string(raw)
				return api.OnLoadResult{Contents: &s, Loader: api.LoaderBinary}, nil
			})
		},
	}
}

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// wasmExports lists the export names of a WebAssembly binary (section 7), in
// the order the binary declares them.
func wasmExports(b []byte) ([]string, error) {
	if len(b) < 8 || string(b[:4]) != "\x00asm" {
		return nil, fmt.Errorf("not a wasm binary")
	}
	pos := 8
	truncated := fmt.Errorf("truncated wasm binary")
	uleb := func() (int, error) {
		v, shift := 0, 0
		for {
			if pos >= len(b) || shift > 28 {
				return 0, truncated
			}
			c := b[pos]
			pos++
			v |= int(c&0x7f) << shift
			if c&0x80 == 0 {
				return v, nil
			}
			shift += 7
		}
	}
	for pos < len(b) {
		id := b[pos]
		pos++
		size, err := uleb()
		if err != nil || pos+size > len(b) {
			return nil, truncated
		}
		if id != 7 {
			pos += size
			continue
		}
		count, err := uleb()
		if err != nil {
			return nil, err
		}
		names := make([]string, 0, count)
		for ; count > 0; count-- {
			l, err := uleb()
			if err != nil || pos+l+1 > len(b) {
				return nil, truncated
			}
			name := string(b[pos : pos+l])
			pos += l + 1                      // the name, then the export-kind byte
			if _, err := uleb(); err != nil { // the export's index
				return nil, err
			}
			if !identRe.MatchString(name) {
				return nil, fmt.Errorf("export %q is not a JavaScript identifier", name)
			}
			names = append(names, name)
		}
		return names, nil
	}
	return nil, fmt.Errorf("no export section")
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: zenoh-ts-bundle <dir holding node_modules> <out.js>")
		os.Exit(2)
	}
	root, err := filepath.Abs(os.Args[1])
	if err == nil {
		root, err = filepath.EvalSymlinks(root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out, err := filepath.Abs(os.Args[2])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	entry := `export * from "@eclipse-zenoh/zenoh-ts";`
	r := api.Build(api.BuildOptions{
		AbsWorkingDir: root,
		Stdin:         &api.StdinOptions{Contents: entry, ResolveDir: root, Loader: api.LoaderJS},
		Bundle:        true,
		Format:        api.FormatESModule,
		Platform:      api.PlatformBrowser,
		Target:        api.ES2022,
		Outfile:       out,
		Write:         true,
		Plugins:       []api.Plugin{wasmPlugin(root)},
		Banner:        map[string]string{"js": banner},
		LegalComments: api.LegalCommentsInline,
		LogLevel:      api.LogLevelWarning,
	})
	if len(r.Errors) > 0 {
		os.Exit(1)
	}
}
